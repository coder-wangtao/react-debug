// 渲染和流式传输的过程
// 当一个请求到达支持 RSC 的服务器时，会发生以下一系列事件：
// 请求进来：用户浏览器请求一个URL
// 路由匹配：服务器的路由系统（比如Next.js App Router）找到对应的页面组件，通常是个服务器组件

// RSC渲染：
// React在服务器上开始渲染页面组件树
// 遇到async服务器组件时，会暂停等数据，但可以继续渲染其他分支
// 生成RSC Payload：这是个特殊的JSON流，不是HTML，而是UI的描述，包含：
// 渲染好的字符串和HTML标签
// 客户端组件的"占位符"和要传给它们的props
// 客户端组件JS文件的引用
// 流式传输：RSC Payload边生成边发送，不等全部完成，浏览器可以尽早开始处理

// 浏览器端处理：

// 浏览器接收RSC Payload流
// React在客户端解析这个流
// 立即把静态、非交互的部分渲染成DOM，用户马上能看到内容（流式HTML效果，FCP很快）
// 遇到客户端组件占位符时，检查对应的JS bundle是否已加载
// 加载客户端JS：如果客户端组件的JS还没加载，React会在<head>里插入<script>标签去请求，通常是并行的

// 水合：客户端组件JS加载完后，React用真实组件替换占位符，附加事件监听器，让它变得可交互。这是选择性、非阻塞的，不像传统SSR要水合整个页面

// 完成：所有可见的客户端组件都水合完毕，页面完全可交互（TTI）

// 整个流程的本质是: 服务器负责执行 RSC、获取数据、编排 UI 结构，并将一份详细的“渲染说明书”（RSC Payload）
// 流式传输给浏览器；浏览器则根据这份说明书，逐步绘制 UI、按需加载交互逻辑并激活它们。
