// React Server Components就是一种只在服务器上跑的React组件。
// 在传统的React组件，不管是SSR还是CSR，最终都要在浏览器里被激活（hydrate）。
// 但RSC不一样，它不会出现在浏览器里。服务器渲染完之后，会生成一种特殊的数据格式（叫RSC Payload），
// 然后流式传输给浏览器，浏览器的React再把这些数据"翻译"成真正的DOM。

// 零客户端包体
// 客户端包体指的是需要下载到用户浏览器中执行的JavaScript代码包。
// 而零客户端包体指服务器组件的代码压根不会出现在浏览器里，在构建出来浏览器javascript产物中不会包含这部分内容。

// 核心规则：
// 数据只能从服务器流向客户端

// 服务器组件可以导入和渲染客户端组件
// 客户端组件不能直接import服务器组件（因为服务器组件代码根本不在客户端）
// 例外：可以把服务器组件作为children传给客户端组件，这是框架帮你做的"魔法"
// 传给客户端的Props必须能序列化

// 从服务器组件传props给客户端组件时，这些props必须能转成JSON
// 能传的：字符串、数字、布尔值、对象、数组、Date
// 不能传的：函数、Class实例等，因为函数代码在服务器上，客户端执行不了
// 这种硬性规定其实约束了我们进行更清晰的架构设计，长远来看是有助于代码的可维护性。

// 数据获取层：肯定是服务器组件
// 交互逻辑层：肯定是客户端组件
// 展示层：静态的用服务器组件，动态的用客户端组件

